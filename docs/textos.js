// Sustituye {clave} por su valor: rellenar('code {c}', { c: 3 }) → 'code 3'
export const rellenar = (s, vals = {}) => String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vals ? vals[k] : m))
